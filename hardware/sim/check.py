#!/usr/bin/env python3
"""Simulate one LVAI channel and check it against expect.toml.

The bench is built from the real schematic, not drawn twice: the channel-0 parts
(sheet "/Low Voltage Analog Input/": U2, RV1, RV2, R1-R7, C5, C6, C17, D2, D3) are
read from the netlist kicad-cli exports, with their own values and nets, so the bench
cannot drift from the board. Each MCP6004 section is an instance of Microchip's
MCP6001/2/4 macro model; each trimmer is two resistors split at its wiper. Added for
the bench only: a 5 V supply, the input source on /Ch0_in and a 0 V ammeter in series
with U2B's + input (pin 5).

Each [[case]] in expect.toml sets the input, the two trimmer positions and the analysis;
each [[measure]] reads one value in that case and compares it with `expect` (+- rtol)
or with `max` (absolute value). Exits 1 on any failure.

Models (hardware/sim/models/):
- MCP6001.txt: Microchip's MCP6001/2/4 SPICE macro model, rev G (MCP6001_MM_G.zip,
  file MCP6001.txt, dated 2024-06-12). Not committed: its licence restricts use to
  Microchip products and does not grant redistribution. Get it from the MCP6004 product
  page, https://www.microchip.com/en-us/product/MCP6004 (Documents > Simulation Models,
  "MCP6001/1R/1U/2/4 SPICE Macro Model"), unzip MCP6001.txt into hardware/sim/models/.
- bas416_standin.lib: a diode fitted to the BAS416 data sheet (Nexperia, 8 Oct 2024):
  VF <= 0.9 V at 1 mA and <= 1.0 V at 10 mA, IR 3 pA typ at 75 V. A stand-in, not
  Nexperia's model.

Usage: python3 hardware/sim/check.py            (needs kicad-cli and ngspice on PATH)
       python3 hardware/sim/check.py --decks    (write the decks to build/ and stop)
       python3 hardware/sim/check.py --logs     (check build/*.log from an earlier run)
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tomllib
import xml.etree.ElementTree as ET
from pathlib import Path

SIM = Path(__file__).resolve().parent
REPO = SIM.parents[1]
BUILD = REPO / "build"
REAL = REPO / "hardware" / "BREAD_Slice.kicad_sch"
MODELS = SIM / "models"
SHEET = "/Low Voltage Analog Input/"
UNITS = {"A": ("3", "2", "1"), "B": ("5", "6", "7"), "C": ("10", "9", "8"), "D": ("12", "13", "14")}
SUFFIX = {"meg": 1e6, "k": 1e3, "m": 1e-3, "u": 1e-6, "n": 1e-9, "p": 1e-12}


def number(text: str) -> float:
    m = re.match(r"([-+]?[0-9.]+)\s*(meg|[kmunp])?", text.strip().lower())
    if not m:
        raise ValueError(f"no number in {text!r}")
    return float(m.group(1)) * SUFFIX.get(m.group(2) or "", 1.0)


def netlist() -> Path:
    out = BUILD / "real.xml"
    if not out.exists():
        subprocess.run(["kicad-cli", "sch", "export", "netlist", "--format", "kicadxml", "-o", str(out), str(REAL)], check=True)
    return out


def channel(xml: Path) -> tuple[dict, dict]:
    """parts of channel 0 (ref -> value) and their pins (ref, pin) -> net."""
    root = ET.parse(xml).getroot()
    parts = {c.get("ref"): c.findtext("value") for c in root.iter("comp")
             if c.find("sheetpath").get("names") == SHEET}
    pins = {}
    for n in root.iter("net"):
        for node in n.iter("node"):
            if node.get("ref") in parts:
                pins[(node.get("ref"), node.get("pin"))] = n.get("name")
    return parts, pins


def node(net: str) -> str:
    if net == "GND":
        return "0"
    if net == "+5V":
        return "vdd"
    net = net.replace("+", "p").replace("-", "m")
    return re.sub(r"[^A-Za-z0-9_]", "_", net).strip("_").lower()


def deck(parts: dict, pins: dict, case: dict, measures: list[dict]) -> str:
    lines = [f"* LVAI channel 0 bench, case {case['name']} (generated by hardware/sim/check.py)",
             ".include models/MCP6001.txt", ".include models/bas416_standin.lib", ".options gmin=1e-12",
             "Vdd vdd 0 DC 5"]
    vin = case.get("vin", 0.0)
    start = case.get("start", 0.0)
    if case["analysis"] == "tran":  # ramp from a linear operating point out to vin, then hold
        lines.append(f"Vin {node('/Ch0_in')} 0 PWL(0 {start} 1m {vin})")
    else:
        lines.append(f"Vin {node('/Ch0_in')} 0 DC {vin} AC 1")
    for ref, value in sorted(parts.items()):
        p = lambda n: node(pins[(ref, n)])  # noqa: E731
        if ref.startswith("RV"):
            total = number(value)
            pos = case["offset"] if pins[(ref, "1")] == "+5V" else case["gain"]  # R(wiper to pin 3) / total
            low = max(total * pos, 1e-3)
            high = max(total * (1 - pos), 1e-3)
            lines += [f"R{ref}a {p('1')} {p('2')} {high:g}", f"R{ref}b {p('2')} {p('3')} {low:g}"]
        elif ref.startswith("R"):
            lines.append(f"{ref} {p('1')} {p('2')} {number(value):g}")
        elif ref.startswith("C"):
            lines.append(f"{ref} {p('1')} {p('2')} {number(value):g}")
        elif ref.startswith("D"):  # Device:D: pin 1 = K, pin 2 = A
            lines.append(f"{ref} {p('2')} {p('1')} BAS416")
        elif ref.startswith("U"):
            for unit, (plus, minus, out) in UNITS.items():
                inp = p(plus)
                if unit == "B":  # ammeter in series with the + input
                    lines.append(f"Viplus {inp} u2b_plus 0")
                    inp = "u2b_plus"
                lines.append(f"X{ref}{unit} {inp} {p(minus)} vdd 0 {p(out)} MCP6001")
    if case["analysis"] == "op":
        lines.append(".op")
        control = ["run"] + [f"let {m['name']} = {m['expr']}" for m in measures] + [f"print {m['name']}" for m in measures]
    elif case["analysis"] == "tran":
        lines.append(".tran 2u 3m")
        control = ["run"] + [f"let {m['name']}_v = {m['expr']}" for m in measures] + \
                  [f"meas tran {m['name']} find {m['name']}_v at=2.9m" for m in measures]
    else:
        lines.append(".ac dec 200 1 100k")
        control = ["run"] + [f"meas ac {m['name']} {m['meas']}" for m in measures]
    return "\n".join(lines + [".control", *control, ".endc", ".end", ""])


def run(path: Path) -> str:
    proc = subprocess.run(["ngspice", "-D", "ngbehavior=ltpsa", "-b", "-o", path.with_suffix(".log").name, path.name],
                          cwd=BUILD, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"ngspice exited {proc.returncode}:\n{proc.stdout}{proc.stderr}")
    return path.with_suffix(".log").read_text(encoding="utf-8", errors="replace")


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    spec = tomllib.loads((SIM / "expect.toml").read_text(encoding="utf-8"))
    if mode != "--logs":
        missing = [t for t in ("kicad-cli",) + (() if mode == "--decks" else ("ngspice",)) if shutil.which(t) is None]
        if missing and not (BUILD / "real.xml").exists():
            print(f"error: not found on PATH: {', '.join(missing)}", file=sys.stderr)
            return 1
        if not (MODELS / "MCP6001.txt").exists():
            print("error: hardware/sim/models/MCP6001.txt missing; see the docstring for where to get it", file=sys.stderr)
            return 1
        BUILD.mkdir(exist_ok=True)
        (BUILD / "models").mkdir(exist_ok=True)
        for f in ("MCP6001.txt", "bas416_standin.lib"):
            shutil.copy(MODELS / f, BUILD / "models" / f)
        parts, pins = channel(netlist())
        print("channel 0 parts:", " ".join(f"{r}={v}" for r, v in sorted(parts.items())))
    failures = []
    for case in spec["case"]:
        measures = [m for m in spec["measure"] if m["case"] == case["name"]]
        path = BUILD / f"lvai_{case['name']}.cir"
        if mode != "--logs":
            path.write_text(deck(parts, pins, case, measures), encoding="utf-8")
            if mode == "--decks":
                continue
            run(path)
        output = path.with_suffix(".log").read_text(encoding="utf-8", errors="replace")
        for m in measures:
            found = re.search(rf"^\s*{re.escape(m['name'])}\s*=\s*([-+0-9.eE]+)", output, re.MULTILINE | re.IGNORECASE)
            if not found:
                failures.append(f"{case['name']}/{m['name']}: ngspice printed no value")
                continue
            value = float(found.group(1))
            if "expect" in m:
                ok = abs(value - m["expect"]) <= m["rtol"] * abs(m["expect"])
                bound = f"expect {m['expect']:.4g} +- {m['rtol'] * 100:g}%"
            elif "max" in m:
                ok = abs(value) <= m["max"]
                bound = f"|value| <= {m['max']:.4g}"
            else:
                ok, bound = True, "informational"
            print(f"{case['name']}/{m['name']} = {value:.4g} ({bound}) {'ok' if ok else 'FAIL'}")
            if not ok:
                failures.append(f"{case['name']}/{m['name']} = {value:.4g}, {bound}")
    for f in failures:
        print(f"error: {f}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
